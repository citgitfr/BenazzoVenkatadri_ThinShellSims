def add_loads(mdl, step, factor, tag):
    sets = mdl.rootAssembly.sets
    for k, (nm, F, Mo) in enumerate(LOADS):
        if any(F):
            mdl.ConcentratedForce(name='%sF%d' % (tag, k), createStepName=step, region=sets[nm],
                                  cf1=factor * F[0] or UNSET, cf2=factor * F[1] or UNSET, cf3=factor * F[2] or UNSET)
        if any(Mo):
            mdl.Moment(name='%sM%d' % (tag, k), createStepName=step, region=sets[nm],
                       cm1=factor * Mo[0] or UNSET, cm2=factor * Mo[1] or UNSET, cm3=factor * Mo[2] or UNSET)


def insert_keyword(mdl, text, before=None, after=None):
    """Insert a keyword block before the first block with a line starting with
    `before` (e.g. '*Step'; blocks may begin with '** STEP:' comments) or after
    the first block with a line starting with `after` (e.g. '*Buckle').
    keywordBlock.insert(i, text) puts the text after block i."""
    mdl.keywordBlock.synchVersions(storeNodesAndElements=False)
    blocks = list(mdl.keywordBlock.sieBlocks)
    key = (before or after).lower()
    for i, blk in enumerate(blocks):
        if any(line.strip().lower().startswith(key) for line in blk.splitlines()):
            mdl.keywordBlock.insert(i - 1 if before else i, text)
            return True
    log('WARNING: keyword block %r not found; %r not inserted' % (before or after, text))
    return False


def buckle_step(mdl, name, previous):
    mdl.BuckleStep(name=name, previous=previous, numEigen=B['n_modes'], vectors=B['n_modes'] + 8,
                   maxIterations=300)


def new_model(name):
    return mdb.Model(name=name, objectToCopy=base)


def run_job(mdl, name):
    job = mdb.Job(name=name, model=mdl.name, type=ANALYSIS, precision=DOUBLE_PRECISION,
                  nodalOutputPrecision=SINGLE, memoryUnits=PERCENTAGE, memory=90)
    job.submit(consistencyChecking=OFF)
    job.waitForCompletion()
    return name


def eigenvalues(job, step):
    odb = openOdb(job + '.odb', readOnly=True)
    out = []
    for fr in odb.steps[step].frames:
        m = re.search(r'EigenValue\s*=\s*([-+0-9.eE]+)', fr.description)
        if m:
            out.append(float(m.group(1)))
    odb.close()
    return out


