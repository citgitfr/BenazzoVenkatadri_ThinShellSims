def point_loads(name, reg, F, M_):
    if any(F):
        model.ConcentratedForce(name=name + 'F', createStepName=STEP, region=reg, **components('cf', F))
    if any(M_):
        model.Moment(name=name + 'M', createStepName=STEP, region=reg, **components('cm', M_))


