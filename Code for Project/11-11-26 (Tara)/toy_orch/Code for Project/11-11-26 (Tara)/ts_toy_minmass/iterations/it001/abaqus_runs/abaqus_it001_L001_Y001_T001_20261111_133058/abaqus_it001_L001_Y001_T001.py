def nearest(p):
    lab, c = min(NODES, key=lambda q: sum((q[1][k] - p[k]) ** 2 for k in range(3)))
    dist = sum((c[k] - p[k]) ** 2 for k in range(3)) ** 0.5
    if dist > TOL:
        log('note: node %d used for point %s is %.3g mm away (mesh size differs from the case)' % (lab, p, dist))
    return lab


