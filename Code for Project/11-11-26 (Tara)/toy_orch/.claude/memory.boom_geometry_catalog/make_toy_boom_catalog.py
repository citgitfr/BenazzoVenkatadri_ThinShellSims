"""Write the TOY boom catalog (boom_geometry_catalog.txt + SVGs) from boom_data.py in this folder,
with the build/check/write functions of the real .claude/memory.boom_geometry_catalog/make_boom_catalog.py.

Usage: python make_toy_boom_catalog.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REAL = os.path.join(HERE, "..", "..", ".claude", "memory.boom_geometry_catalog")
sys.path.insert(0, HERE)            # toy boom_data first
sys.path.insert(1, REAL)            # real boom_geometry / make_boom_catalog
from boom_data import GEOMETRIES, SELECTED  # noqa: E402
import make_boom_catalog as mbc  # noqa: E402

assert os.path.dirname(os.path.abspath(sys.modules["boom_data"].__file__)) == HERE, "picked up the real boom_data"

mbc.HEAD_NOTES = mbc.HEAD_NOTES.replace(
    "# Coilable boom cross-section catalog (read by the ThinShellOrchestrator agent).\n"
    "# GENERATED by make_boom_catalog.py from boom_data.py; edit boom_data.py, then rerun.\n",
    "# Coilable boom cross-section catalog -- TOY CATALOG for the Tape Spring Baseline demo.\n"
    "# Same format as .claude/memory.boom_geometry_catalog/boom_geometry_catalog.txt (do not mix with it).\n"
    "# GENERATED by make_toy_boom_catalog.py from boom_data.py (this folder); edit boom_data.py, then rerun.\n")


def main():
    built = [(g, mbc.build(g)) for g in GEOMETRIES]
    rows = [mbc.row(g, b) for g, b in built]
    notes = ["# Per-ID notes"] + [f"#  {g['id']} {g['note']}" for g in GEOMETRIES if g.get("note")]
    mbc.write_catalog(rows, notes, os.path.join(HERE, "boom_geometry_catalog.txt"))
    mbc.svg(built, os.path.join(HERE, "boom_sections_all.svg"), 3, (300, 240),
            "Toy tape spring cross-sections (each panel scaled to fit)")
    for g, b in built:
        for p in b["problems"]:
            print(f"FAIL {g['id']}: {p}")
    print(f"{len(GEOMETRIES)} geometries written to {HERE}")


if __name__ == "__main__":
    main()
