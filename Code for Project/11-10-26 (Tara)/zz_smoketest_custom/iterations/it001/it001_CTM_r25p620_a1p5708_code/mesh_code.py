ELEMENT, OPTIONS, EAS = 'ASDShellQ4', (), None


def facet_frame(p1, p2, p3, p4):
    # e1 (along the x edges), e2, n of a facet; n = (n1->n3) x (n2->n4)
    n = np.cross(p3 - p1, p4 - p2)
    n /= np.linalg.norm(n)
    e1 = (p2 - p1) + (p3 - p4)
    e1 -= n * (e1 @ n)
    e1 /= np.linalg.norm(e1)
    return e1, np.cross(n, e1), n


