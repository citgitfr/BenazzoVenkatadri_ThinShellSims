LOADS = []                 # (set name, force, moment) per unit reference load
for k, ld in enumerate(M['loads']):
    if ld['kind'] == 'rigid':
        LOADS.append(('RP-' + ld['edge'].upper(), ld['F'], ld['M']))
    elif ld['kind'] == 'node':
        node_set([nearest(ld['point'])], 'LOAD%d' % k)
        LOADS.append(('LOAD%d' % k, ld['F'], ld['M']))
    elif ld['kind'] == 'edge':
        groups = {}
        for lab, w in zip(*edge_nodes(ld['edge'])):
            groups.setdefault(round(w, 12), []).append(lab)
        for g, (w, labs) in enumerate(sorted(groups.items())):
            node_set(labs, 'LOAD%d_%d' % (k, g))
            LOADS.append(('LOAD%d_%d' % (k, g), [w * f for f in ld['F']], [w * m for m in ld['M']]))
    else:
        raise ValueError('pressure loads are not exported for buckling')


def point_set(spec, name):
    """Region name of a monitor/control point: rigid-end RP or nearest shell node."""
    if 'rigid' in spec:
        return 'RP-' + spec['rigid'].upper()
    node_set([nearest(spec['point'])], name)
    return name


