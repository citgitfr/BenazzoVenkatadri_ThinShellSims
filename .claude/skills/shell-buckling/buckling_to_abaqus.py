"""
Abaqus/CAE script for the buckling cross-check of an OpenSeesPy buckling case
(shell-buckling skill; ToDo item 8). Reuses the model builder of the
abaqus-export skill (geometry, laminate, structured mesh identical to
shell-mesh, rigid ends as KINEMATIC couplings, supports, consistent edge
loads) and replaces its analysis with the three Abaqus buckling procedures
of the literature:

  1. LBA      *BUCKLE (linear perturbation) with the reference load:
              critical load factors and modes (job <name>_LBA, writes the .fil
              used for the imperfection).
  2. NLB      "nonlinear buckling load" of Palmeri & Laurenzi (2024) and
              Leclerc & Pellegrino (2020): nonlinear static preload to
              f x lambda_LBA, then *BUCKLE about the deformed state; critical =
              preload + perturbation eigenvalue (one job per fraction f).
  3. RIKS     *IMPERFECTION (mode 1 of the LBA, given amplitude) + Riks: peak
              load proportionality factor = buckling strength; for a stable
              post-buckling path (columns) a Southwell fit on a monitor node.

The reference load of the case is scaled by `scale` (an estimate of the
critical load) so that load factors are of order 1; every result is reported
in the case's load units (N or N mm) and compared with the OpenSees /
analytical values given in the case ("reference").

Case file (shell-bc-load format + a "buckling" block):
{
 "name": "tape_opp_bending_L200",
 "laminate": {"isotropic": {"E": 131000, "nu": 0.3, "t": 0.1}},
 "geometry": {"L": 200, "section": {"type": "arc", "R": 13.3, "b": 24.605}, "size": 2},
 "supports": [{"rigid_end": "x0", "dofs": [1,1,1,1,1,1]}, {"rigid_end": "xL", "dofs": [0,1,0,1,0,1]}],
 "loads": [{"node": {"rigid": "xL"}, "moment": [0, 1, 0]}],
 "buckling": {"scale": 400, "n_modes": 4, "preload_fractions": [0.5, 0.8, 0.95],
              "riks": {"amplitude": 0.01, "control": {"rigid": "xL", "dof": 5}, "max_disp": 0.3,
                       "max_lpf": 2.0, "max_inc": 200},
              "monitor": {"rigid": "xL", "dof": 5}},
 "reference": {"OpenSees A (ShellNLDKGQ K_T eigen)": 311.5, "OpenSees B ASDShellQ4 peak": 394.9}
}
monitor / control: {"rigid": edge, "dof": d} or {"x": .., "s": .., "dof": d} (a shell node).

    python buckling_to_abaqus.py case.json [--out abaqus_<name>_buckling.py] [--element S4R|S4]
    abaqus cae noGUI=abaqus_<name>_buckling.py [-- <size> <S4R|S4>]
NOT RUN IN ABAQUS when written (no Abaqus on the project VM); the model-building
part runs on the stand-in API of regression-tests/abaqus_mock.py (--mock).
"""
