def generate(case_path, out=None, element='S4R'):
    case = json.loads(Path(case_path).read_text())
    spec = dict(case['laminate'])
    if 'json' in spec and not Path(spec['json']).is_absolute():
        spec['json'] = str(Path(case_path).parent / spec['json'])
        case['laminate'] = spec
    lam = lp.laminate_from_spec(spec)
    mesh = sm.build_from_spec(case['geometry'])
    mesh.size = case['geometry']['size']
    model = ca.describe_model(case, mesh, lam)
    bk = dict(case['buckling'])
    for key in ('monitor',):
        if bk.get(key) and 'rigid' not in bk[key]:
            bk[key] = dict(bk[key], point=ca.node_point(mesh, {k: bk[key][k] for k in ('x', 's')}))
    ctrl = bk['riks'].get('control')
    if ctrl and 'rigid' not in ctrl:
        bk['riks'] = dict(bk['riks'], control=dict(ctrl, point=ca.node_point(mesh, {k: ctrl[k] for k in ('x', 's')})))
    name = model['name']
    out = Path(out) if out else Path(case_path).parent / f'abaqus_{name}_buckling.py'
    summary = '\n'.join([
        f'Geometry: {mesh.summary()}',
        f'Section:  {lam.describe()}',
        f'Supports: {json.dumps(case.get("supports", []))}',
        f'Loads (reference, x scale {bk["scale"]:g}): {json.dumps(case.get("loads", []))}',
        f'Buckling: {json.dumps(case["buckling"])}',
        f'Reference values: {json.dumps(case.get("reference", {}))}'])
    text = (_PREFIX + _BUCKLE) % dict(
        name=name, case_file=Path(case_path).name, summary=summary, script=out.name, size=mesh.size,
        element=element, job=name.replace('-', '_')[:24], model=ca._literal(model), ref='{}',
        buckling=ca._literal(bk), reference=ca._literal(case.get('reference', {})))
    out.write_text(text, encoding='utf-8')
    return out, model, case


def mock_run(script, case):
    """Execute the script on the stand-in Abaqus API (regression-tests/abaqus_mock.py)
    up to the first job submission; returns the call log."""
    sys.path.insert(0, str(_HERE.parent / 'regression-tests'))
    import abaqus_mock as am
    mesh = sm.build_from_spec(case['geometry'])
    nodes = [mesh.coords(i, j) for j in range(mesh.ny + 1) for i in range(mesh.nx + 1)]
    log = am.install(nodes, lambda p: (0.0, 0.0, 0.0))
    mdb = sys.modules['abaqus'].mdb
    real_model = type(mdb).Model

    def model(self, name, objectToCopy=None):           # the regression mock has no model copies
        import collections
        m = real_model(self, name)
        m.__dict__['rootAssembly'].__dict__['sets'] = collections.defaultdict(lambda: ('SET', 'copied'))
        log.append(('mdb.Model', (), dict(name=name, copy=objectToCopy is not None)))
        return m
    type(mdb).Model = model
    import os
    cwd = os.getcwd()
    os.chdir(Path(script).parent)
    try:
        exec(compile(Path(script).read_text(encoding='utf-8'), str(script), 'exec'), {'__name__': '__main__'})
    except am.StopAtJob:
        pass
    finally:
        os.chdir(cwd)
        type(mdb).Model = real_model
    return log


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('case')
    ap.add_argument('--out')
    ap.add_argument('--element', default='S4R', choices=('S4R', 'S4'))
    ap.add_argument('--mock', action='store_true', help='also run the model-building part on the stand-in API')
    a = ap.parse_args()
    out, model, case = generate(a.case, a.out, a.element)
    print(f'wrote {out}')
    if a.mock:
        calls = mock_run(out, case)
        names = [c[0] for c in calls]
        print(f'  mock run: {len(calls)} API calls up to the first job; '
              f'BuckleStep {sum(n.endswith("BuckleStep") for n in names)}, '
              f'StaticRiksStep {sum(n.endswith("StaticRiksStep") for n in names)}, '
              f'DisplacementBC {sum(n.endswith("DisplacementBC") for n in names)}, '
              f'ConcentratedForce {sum(n.endswith("ConcentratedForce") for n in names)}, '
              f'Moment {sum(n.endswith(".Moment") for n in names)}, '
              f'Coupling {sum(n.endswith("Coupling") for n in names)}, '
              f'keyword inserts {sum(n.endswith("keywordBlock.insert") for n in names)}')


if __name__ == '__main__':
    main()
