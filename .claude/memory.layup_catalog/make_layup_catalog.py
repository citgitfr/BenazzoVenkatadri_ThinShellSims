"""Write the layup catalog: every symmetric stacking sequence of 1 to 5 plies
with ply angles 0, 15, ..., 90 deg.

Usage: python make_layup_catalog.py [out.txt]

A symmetric layup of n plies is fixed by its first ceil(n/2) plies (bottom
to the mid-plane), so there are 7^ceil(n/2) layups per ply count:
7 + 7 + 49 + 49 + 343 = 455. Layups are listed bottom (-z) to top (+z) as
the full sequence, e.g. [0/45/0], which laminate_properties.py --layup reads
directly. Columns are space-aligned, like the material catalog.
"""
import itertools
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "layup_catalog.txt")
ANGLES = tuple(range(0, 91, 15))
N_PLIES = range(1, 6)
T_PLY = 0.035  # mm, the t_ply of every row in the material catalog
SEP = "   "


def layups():
    for n in N_PLIES:
        for half in itertools.product(ANGLES, repeat=math.ceil(n / 2)):
            yield list(half) + list(half[:n // 2])[::-1]


def row(i, seq):
    distinct = sorted(set(seq))
    return [
        f"Y{i:03d}",
        str(len(seq)),
        "[" + "/".join(str(a) for a in seq) + "]",
        f"{len(seq) * T_PLY:.3f}",
        str(len(distinct)),
        "/".join(str(a) for a in distinct),
        "yes" if set(seq) <= {0, 90} else "no",
    ]


HEADER = ["ID", "n_plies", "layup", "h_mm", "n_angles", "angles", "cross_ply"]

NOTES = f"""\
# Layup catalog for the thin-shell simulations (read by the ThinShellOrchestrator agent).
# GENERATED by make_layup_catalog.py; edit the script, not this file.
#
# Contents: every SYMMETRIC stacking sequence of 1 to 5 plies with ply angles 0, 15, 30, 45, 60, 75, 90 deg
#   (no negative angles). {{counts}}
#
# Columns
#   ID         Y001, Y002, ...
#   n_plies    number of plies
#   layup      full stacking sequence, bottom (-z) to top (+z), angles in deg from the shell x axis (extrusion
#              axis), CCW about the normal. Pass it as is: laminate_properties.py --layup "[0/45/0]".
#   h_mm       laminate thickness with t_ply = {T_PLY} mm (the t_ply of every material-catalog row).
#   n_angles   number of distinct angles = coincident ASDShellQ4 elements per facet (run cost grows with it).
#   angles     the distinct angles.
#   cross_ply  yes if only 0 and 90 plies (A16 = A26 = D16 = D26 = 0, no extension-shear or bend-twist coupling).
#
# Mechanics to keep in mind when picking
#   - Symmetric, so B = 0 for every row (no extension-bending coupling).
#   - Angles are 0..90 only, so any layup with a 15-75 deg ply is unbalanced: A16, A26 != 0 (extension-shear
#     coupling) and D16, D26 != 0 (bend-twist coupling). Only cross_ply = yes rows are free of both.
#   - 1- and 2-ply layups are single angle-ply laminates; laminate-properties splits each ply into n_sub layers
#     (LayeredShell needs >= 3 layers), so they run, but treat them as UD sheets.
#
"""


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUT
    table = [row(i, seq) for i, seq in enumerate(layups(), 1)]
    per_n = {n: sum(1 for r in table if r[1] == str(n)) for n in N_PLIES}
    counts = f"{len(table)} layups: " + ", ".join(f"{c} with {n} pl{'y' if n == 1 else 'ies'}" for n, c in per_n.items()) + "."
    widths = [max(len(r[i]) for r in [HEADER] + table) for i in range(len(HEADER) - 1)]
    with open(out, "w", encoding="utf-8") as f:
        f.write(NOTES.replace("{counts}", counts))
        for r in [HEADER] + table:
            f.write(SEP.join(c.ljust(w) for c, w in zip(r, widths)) + SEP + r[-1] + "\n")
    print(f"{counts}\nwritten to {out}")


if __name__ == "__main__":
    main()
